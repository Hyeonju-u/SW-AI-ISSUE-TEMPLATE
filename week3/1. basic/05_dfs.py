"""
[DFS - 깊이 우선 탐색 (Depth-First Search)]

문제 설명:
- DFS로 그래프를 탐색합니다.
- 깊이 방향으로 끝까지 탐색합니다.
- 재귀 또는 스택을 사용합니다.

입력:
- graph: 그래프 (인접 리스트)
- start: 시작 정점

출력:
- 방문 순서

예제:
그래프:
  0 ─── 1
  │     │
  └─ 2 ─┘
      │
      3

시작: 0
DFS: [0, 1, 2, 3] (순서는 구현에 따라 다를 수 있음)

힌트:
- 재귀로 구현
- 방문 체크 필요
- 깊이 우선으로 방문
"""
# DFS 핵심
# 한놈만 패는 알고리즘
# 깊은 것을 우선적으로 탐색하는 알고리즘
# 스택이나 재귀 사용(사실 스택을 사용하지 않아도 구현가능함 컴퓨터는 구조적으로 항상 스택의 원리를 사용)
# 맨처음에 시작노드를 스택에 삽입하면서 시작 그와 동시에 시작 노드에 방문 했다고 방문 처리를 해줘야함
# 다음과 같은 알고리즘에 의해 작동
# 1 스택에 최상단 노드를 확인
# 2.최상단 노드에 방문하지 않은 인접 노드가 있으면 그 스택에 노드를 넣고 방문 처리
# 3 방문하지않은 인접 노드가 없으면 스택에서 최상단 노드를 뺌
# 4.큐가 빌때까지 해당 동작 반복
def dfs(graph, start, visited=None):
    """
    깊이 우선 탐색 (재귀)
    
    Args:
        graph: 그래프 딕셔너리
        start: 현재 정점 # # start는 항상 이번 재귀에서 다루는 장점을 가리킴,첫 호출에서만 진짜 시작점이고 그 다음 부터는 재귀가 도달한 정점이라는 의미로 계속 사용 됨
        visited: 방문 리스트
    
    Returns:
        방문 순서 리스트
    """
    # TODO: visited가 None이면 초기화
    if visited is None: 
        visited = [] #return []을 하면 함수가 종료 됨
    
    # TODO: 현재 정점 방문
    visited.append(start) # start = 이번 재귀 실행의 "현재 정점" (재귀마다 값이 바뀜, 이름만 고정)
    
    
    
    # TODO: 인접한 정점들에 대해 재귀
    ## 방문하지 않은 정점이면 재귀 호출
    for n in graph[start]: #start 의 이웃 정점들을 확인
        if n not in visited: # n이 아직 방문 하지않은 정점이면
            dfs(graph, n, visited) #n을 새로운 현재 정점으로 삼아 재귀 호출 이 호출에서는 start가 새로운 n이됨


    
    return visited

# 테스트 케이스
if __name__ == "__main__":
    # 그래프 생성
    graph = {
        0: [1, 2],
        1: [0, 2],
        2: [0, 1, 3],
        3: [2]
    }
    
    print("=== DFS (깊이 우선 탐색) ===")
    result = dfs(graph, 0)
    print(f"시작 정점: 0")
    print(f"방문 순서: {result}")


